using NewsQuack.App.Fetching;
using Xunit;

namespace NewsQuack.App.Tests;

/// <summary>T-010 robots parser unit tests: the dedicated, pure, tolerant parser must never throw on malformed input — a line without ':' is
/// skipped and counted, not an exception. Matching: '*' / 'newsquack' (case-insensitive), longest matching path prefix wins, Allow beats
/// Disallow on a tie, a bare "Disallow:" with an empty value allows everything. Fixtures are explicit string arrays so tabs/trailing spaces
/// in the source are unambiguous.</summary>
public class RobotsParserTests
{
    [Fact]
    public void RobotsParser_UserAgentStar_DisallowPath_MatchesFeedUnderThatPath()
    {
        var robots = Lines("User-agent: *", "Disallow: /private/");

        Assert.False(RobotsParser.Parse(robots, "/private/feed.xml").Allowed);   // under the disallowed prefix…
        Assert.True(RobotsParser.Parse(robots, "/public/feed.xml").Allowed);     // …but outside it is allowed
    }

    [Fact]
    public void RobotsParser_SpacesAroundTokens_And_Comments_ParsedCorrectly()
    {
        var robots = Lines(
            "# generated by the host — a comment line",
            "",                              // blank line (whitespace-only would be the same)
            "  User-agent :   *  ",          // spaces around the key AND trailing spaces in the value…
            " Disallow :     /a/b   ");      // …and leading space before the key

        Assert.False(RobotsParser.Parse(robots, "/a/b/c/feed.xml").Allowed);   // "User-agent :" (space before the colon) + trimmed values still match…
        Assert.True(RobotsParser.Parse(robots, "/x/feed.xml").Allowed);        // …and comments/blank lines are simply skipped
    }

    [Fact]
    public void RobotsParser_MalformedLinesWithoutColon_SkippedAndCountedNeverThrows()
    {
        var robots = Lines(
            "garbage line without a colon",  // malformed (1) — no ':' at all…
            "",                              // blank — skipped, not counted…
            "\t\t",                          // whitespace-only — skipped, not counted…
            "# a comment",                   // comment — skipped, not counted…
            "no-colon-here",                 // malformed (2)…
            "User-agent: *",                 // valid agent line after the garbage…
            "Disallow:",                     // bare Disallow with an empty value — allows everything…
            "Allow:   ",                     // …and a trailing-space value that trims to empty…
            "Sitemap: /sitemap.xml");        // another directive — present and valid, just not ours

        var result = RobotsParser.Parse(robots, "/anything/feed.xml");   // never throws — malformed lines are data, not exceptions

        Assert.Equal(2, result.MalformedLineCount);   // exactly the two colon-less lines…
        Assert.True(result.Allowed);                 // …and a bare "Disallow:" with an empty value allows everything
    }

    [Fact]
    public void RobotsParser_AllowBeatsDisallow_LongestPrefixWins()
    {
        var robots = Lines("User-agent: *", "Disallow: /a", "Allow: /ab");

        Assert.True(RobotsParser.Parse(robots, "/abc/feed.xml").Allowed);   // "/ab" (Allow) is the longest matching prefix…
        Assert.False(RobotsParser.Parse(robots, "/ax/feed.xml").Allowed);   // …whereas only "/a" (Disallow) matches there

        var tie = Lines("User-agent: *", "Disallow: /x", "Allow: /x");

        Assert.True(RobotsParser.Parse(tie, "/xy/feed.xml").Allowed);   // equal-length prefix: Allow beats Disallow
    }

    [Fact]
    public void RobotsParser_NewsquackAgent_CaseInsensitive_MatchesOwnBlockOnly()
    {
        var robots = Lines(
            "User-agent: Googlebot",
            "Disallow: /google-only/",
            "",
            "User-agent: NEWSQUACK",          // uppercase — must still match our product token…
            "Disallow: /newsquack-only/");

        Assert.False(RobotsParser.Parse(robots, "/newsquack-only/feed.xml").Allowed);   // "NEWSQUACK" matches case-insensitively…
        Assert.True(RobotsParser.Parse(robots, "/google-only/feed.xml").Allowed);       // …and the Googlebot block does not apply to us
    }

    [Fact]
    public void RobotsParser_EmptyOrNullOrText_AllowsEverything()
    {
        Assert.True(RobotsParser.Parse(null, "/feed.xml").Allowed);
        Assert.True(RobotsParser.Parse("", "/feed.xml").Allowed);
        Assert.Equal(0, RobotsParser.Parse("  \n# only comments\n", "/feed.xml").MalformedLineCount);
    }

    private static string Lines(params string[] lines) => string.Join("\n", lines);
}
